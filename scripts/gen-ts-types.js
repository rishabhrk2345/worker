/**
 * scripts/gen-ts-types.js
 * 
 * Generates authoritative TypeScript interfaces and types from `contracts/` JSON schemas into
 * `apps/web/lib/types/generated/`.
 */

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const CONTRACTS_DIR = path.join(ROOT_DIR, 'contracts');
const ENUMS_DIR = path.join(CONTRACTS_DIR, 'enums');
const OUT_DIR = path.join(ROOT_DIR, 'apps', 'web', 'lib', 'types', 'generated');

function loadJson(filepath) {
  return JSON.parse(fs.readFileSync(filepath, 'utf-8'));
}

function generateEnums() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const outFile = path.join(OUT_DIR, 'enums.ts');

  const workerEventTypes = loadJson(path.join(ENUMS_DIR, 'worker_event_type.json')).enum;
  const workerStatesData = loadJson(path.join(ENUMS_DIR, 'worker_state.json'));
  const workerStates = workerStatesData.enum;
  const stateTransitions = workerStatesData['x-transitions'] || {};
  const stateAnimationMap = workerStatesData['x-3d-animation-map'] || {};
  const logicalZones = loadJson(path.join(ENUMS_DIR, 'logical_zone.json'))['x-zone-enum'];
  const workerTypesData = loadJson(path.join(ENUMS_DIR, 'worker_type.json'));
  const workerTypes = workerTypesData.enum;
  const workerTypeZoneDefaults = workerTypesData['x-zone-defaults'] || {};
  const sourceCapabilities = loadJson(path.join(ENUMS_DIR, 'source_capability.json')).enum;

  const lines = [
    '/**',
    ' * AUTOGENERATED FILE — DO NOT EDIT DIRECTLY',
    ' * Generated from contracts/enums/ by scripts/gen-ts-types.js',
    ' */',
    '',
    'export type WorkerEventType =',
    ...workerEventTypes.map(t => `  | '${t}'`),
    ';',
    '',
    'export type WorkerState =',
    ...workerStates.map(s => `  | '${s}'`),
    ';',
    '',
    'export type LogicalZone =',
    ...logicalZones.map(z => `  | '${z}'`),
    ';',
    '',
    'export type WorkerType =',
    ...workerTypes.map(w => `  | '${w}'`),
    ';',
    '',
    'export type SourceCapability =',
    ...sourceCapabilities.map(c => `  | '${c}'`),
    ';',
    '',
    'export const WORKER_STATE_TRANSITIONS: Record<WorkerState, WorkerState[]> = {',
    ...Object.entries(stateTransitions).map(([state, targets]) => 
      `  ${state}: [${targets.map(t => `'${t}'`).join(', ')}],`
    ),
    '};',
    '',
    'export const WORKER_ANIMATION_MAP: Record<WorkerState, string> = {',
    ...Object.entries(stateAnimationMap).map(([state, anim]) => 
      `  ${state}: '${anim}',`
    ),
    '};',
    '',
    'export const WORKER_TYPE_DEFAULT_ZONES: Record<WorkerType, LogicalZone> = {',
    ...Object.entries(workerTypeZoneDefaults).map(([wt, zone]) => 
      `  ${wt}: '${zone}',`
    ),
    '};',
    ''
  ];

  fs.writeFileSync(outFile, lines.join('\n'), 'utf-8');
  console.log(`  ✓ Generated apps/web/lib/types/generated/enums.ts`);
}

